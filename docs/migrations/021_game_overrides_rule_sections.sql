-- 021_game_overrides_rule_sections.sql
-- 게임 방법을 하나의 rule_note 텍스트가 아니라 목표/준비/진행/종료 4개 슬롯으로 구조화.
--
-- 배경: 52개 게임 룰을 관리자가 손으로 입력할 예정. rule_note 하나에 소제목까지 직접
-- 타이핑하게 하면(빈 줄 규칙 기억, 서식 깨짐) 반복 입력 부담이 크다 — 칸을 나눠서
-- 관리자는 각 칸에 본문만 붙여넣고, 프론트가 자동으로 안내형 제목("게임 목표"/
-- "먼저 준비하세요"/"게임은 이렇게 진행해요"/"게임이 끝나면")을 붙인다.
-- 빈 칸은 프론트에서 자동으로 숨긴다(예: 도블처럼 준비가 필요 없는 게임은 setup 생략).
--
-- 컬럼 4개 대신 jsonb 1개인 이유: 나중에 슬롯이 하나 더 필요해져도 마이그레이션 없이
-- 키만 추가하면 된다. 키: goal(게임 목표) / setup(준비하기) / play(게임 진행) / end(게임 종료),
-- 전부 선택 입력(없는 키는 그냥 안 씀).
--
-- rule_note(기존 텍스트 컬럼)는 삭제하지 않는다 — 지금 있는 3건은 "ㅎㅇ" 같은 테스트
-- placeholder라 보존할 실데이터가 없고, 컬럼 자체는 건드리지 않는 게 더 안전하다.

ALTER TABLE public.game_overrides ADD COLUMN IF NOT EXISTS rule_sections JSONB;

